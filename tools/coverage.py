#!/usr/bin/env python3
"""Build ATT&CK coverage artefacts from the rules and the mapping.

Outputs (all deterministic, regenerated by CI and checked for drift):
  coverage/attack-navigator-layer.json  layer for https://mitre-attack.github.io/attack-navigator/
  coverage/coverage.md                  tactic -> technique -> rule summary tables
  coverage/coverage-heatmap.svg         static heatmap for the README

Scoring: a technique's score is the number of rules that detect it (under that tactic).
"Covered" means "at least one rule exists and passes the synthetic tests in CI"; it does
NOT mean the technique is fully detected in every variant - see docs/technical-note.md.

    python tools/coverage.py
"""

from __future__ import annotations

import html
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dac_common import ATTACK_VERSION, REPO_ROOT, load_attack, load_mapping, load_rules  # noqa: E402

OUT = REPO_ROOT / "coverage"
NAVIGATOR_URL = "https://mitre-attack.github.io/attack-navigator/"

# Ordinal blue ramp (1, 2, 3+ rules) and neutral for "not covered"; validated with the
# dataviz palette validator against the light surface #fcfcfb.
SCORE_COLORS = {1: "#86b6ef", 2: "#3987e5", 3: "#184f95"}
SURFACE = "#fcfcfb"
INK, INK_MUTED, EMPTY = "#0b0b0b", "#52514e", "#f0efec"


def collect():
    attack = load_attack()
    mapping = {d["rule"]: d for d in load_mapping()["detections"]}
    rules = load_rules()
    # (technique, tactic) -> list of rules
    cells: dict[tuple[str, str], list] = defaultdict(list)
    for r in rules:
        for tid in r.techniques:
            for tactic in attack["techniques"][tid]["tactics"]:
                if tactic in r.tactic_tags:
                    cells[(tid, tactic)].append(r)
    return attack, mapping, rules, cells


def short_to_tid(attack: dict) -> dict[str, str]:
    return {t["shortname"]: tid for tid, t in attack["tactics"].items()}


def tactic_totals(attack: dict) -> dict[str, int]:
    """Number of techniques + sub-techniques per tactic in the pinned ATT&CK release."""
    totals: dict[str, int] = defaultdict(int)
    for t in attack["techniques"].values():
        for tactic in t["tactics"]:
            totals[tactic] += 1
    return totals


def build_layer(attack, mapping, cells) -> dict:
    techniques = []
    parents_needed: set[tuple[str, str]] = set()
    for (tid, tactic), rules in sorted(cells.items()):
        score = len(rules)
        lab = sorted({mapping[r.rel]["lab_validation"] for r in rules})
        techniques.append({
            "techniqueID": tid,
            "tactic": tactic,
            "score": score,
            "color": "",
            "comment": "; ".join(r.data["title"] for r in rules),
            "enabled": True,
            "metadata": [{"name": "rule", "value": r.rel} for r in rules]
            + [{"name": "lab_validation", "value": ", ".join(lab)}],
            "links": [],
            "showSubtechniques": False,
        })
        if "." in tid:
            parents_needed.add((tid.split(".")[0], tactic))
    for parent, tactic in sorted(parents_needed):
        if (parent, tactic) not in cells:
            techniques.append({
                "techniqueID": parent, "tactic": tactic, "color": "", "comment": "",
                "enabled": True, "metadata": [], "links": [], "showSubtechniques": True,
            })
        else:
            for t in techniques:
                if t["techniqueID"] == parent and t["tactic"] == tactic:
                    t["showSubtechniques"] = True

    return {
        "name": "Detection-as-Code coverage",
        "versions": {"attack": ATTACK_VERSION.split(".")[0], "navigator": "5.3.2", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": (
            f"Generated by tools/coverage.py from rules/ and mapping/detections.yml against "
            f"Enterprise ATT&CK v{ATTACK_VERSION}. Score = number of Sigma rules detecting the "
            "technique under that tactic."
        ),
        "sorting": 3,
        "layout": {"layout": "side", "aggregateFunction": "max", "showID": True,
                   "showName": True, "showAggregateScores": False, "countUnscored": False,
                   "expandedSubtechniques": "annotated"},
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": [SCORE_COLORS[1], SCORE_COLORS[3]], "minValue": 1, "maxValue": 3},
        "legendItems": [
            {"label": "1 rule", "color": SCORE_COLORS[1]},
            {"label": "2 rules", "color": SCORE_COLORS[2]},
            {"label": "3+ rules", "color": SCORE_COLORS[3]},
        ],
        "metadata": [{"name": "attack_version", "value": ATTACK_VERSION}],
        "links": [],
        "showTacticRowBackground": False,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": False,
        "selectSubtechniquesWithParent": False,
        "selectVisibleTechniques": False,
    }


def build_markdown(attack, mapping, rules, cells) -> str:
    totals = tactic_totals(attack)
    by_tactic: dict[str, dict[str, list]] = defaultdict(dict)
    for (tid, tactic), rs in cells.items():
        by_tactic[tactic][tid] = rs
    tech_ids = sorted({tid for tid, _ in cells})
    order = [attack["tactics"][t]["shortname"] for t in attack["tactic_order"]]
    covered_tactics = [t for t in order if t in by_tactic]
    tid_of = short_to_tid(attack)

    lines = [
        "# ATT&CK coverage summary",
        "",
        f"> GENERATED by `tools/coverage.py` against Enterprise ATT&CK v{ATTACK_VERSION} - do not edit.",
        "> \"Covered\" = at least one rule exists and passes the synthetic tests; it is not a claim",
        "> of complete detection of every procedure of the technique.",
        "",
        f"- Rules: **{len(rules)}**",
        f"- Distinct techniques / sub-techniques detected: **{len(tech_ids)}**",
        f"- Tactics with at least one detection: **{len(covered_tactics)} of {len(order)}**",
        "",
        "## Tactic overview",
        "",
        "| Tactic | Techniques covered | Techniques in ATT&CK | Share | Rules |",
        "|---|---:|---:|---:|---:|",
    ]
    for tactic in order:
        techs = by_tactic.get(tactic, {})
        nrules = len({r.rel for rs in techs.values() for r in rs})
        share = f"{100 * len(techs) / totals[tactic]:.1f}%" if totals[tactic] else "-"
        name = attack["tactics"][tid_of[tactic]]["name"]
        lines.append(f"| {name} ({tid_of[tactic]}) | {len(techs)} | {totals[tactic]} | {share} | {nrules} |")

    lines += ["", "## Tactic -> technique -> rule", ""]
    for tactic in covered_tactics:
        name = attack["tactics"][tid_of[tactic]]["name"]
        lines += [f"### {name} ({tid_of[tactic]})", "",
                  "| Technique | Name | Rules | Lab validation |", "|---|---|---|---|"]
        for tid in sorted(by_tactic[tactic]):
            rs = by_tactic[tactic][tid]
            link = f"[{tid}](https://attack.mitre.org/techniques/{tid.replace('.', '/')}/)"
            rule_links = "<br>".join(f"[{r.data['title']}](../{r.rel})" for r in rs)
            lab = ", ".join(sorted({mapping[r.rel]["lab_validation"] for r in rs}))
            lines.append(f"| {link} | {attack['techniques'][tid]['name']} | {rule_links} | {lab} |")
        lines.append("")

    lines += [
        "## View the heatmap in ATT&CK Navigator",
        "",
        f"1. Open {NAVIGATOR_URL}",
        "2. *Open Existing Layer* -> *Upload from local* -> `coverage/attack-navigator-layer.json`",
        "   (or *Load from URL* with the raw GitHub URL of that file).",
        "",
    ]
    return "\n".join(lines)


def build_svg(attack, cells) -> str:
    order = [attack["tactics"][t]["shortname"] for t in attack["tactic_order"]]
    tid_of = short_to_tid(attack)
    totals = tactic_totals(attack)
    by_tactic: dict[str, list[tuple[str, int]]] = defaultdict(list)
    for (tid, tactic), rs in sorted(cells.items()):
        by_tactic[tactic].append((tid, len(rs)))

    col_w, gap, cell_h, head_h, pad = 118, 4, 34, 58, 16
    max_cells = max((len(v) for v in by_tactic.values()), default=0)
    width = pad * 2 + len(order) * (col_w + gap) - gap
    legend_y = pad + 34 + head_h + max(max_cells, 1) * (cell_h + gap) + 14
    height = legend_y + 40
    e = html.escape
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" font-family="Segoe UI, Helvetica, Arial, sans-serif" '
        f'role="img" aria-labelledby="t d">',
        f'<title id="t">ATT&amp;CK coverage heatmap (Enterprise v{ATTACK_VERSION})</title>',
        '<desc id="d">Columns are ATT&amp;CK tactics; each cell is a technique detected by at least '
        'one rule; darker blue means more rules.</desc>',
        f'<rect width="{width}" height="{height}" fill="{SURFACE}"/>',
        f'<text x="{pad}" y="{pad + 16}" font-size="16" font-weight="600" fill="{INK}">'
        f'ATT&amp;CK coverage - Enterprise v{ATTACK_VERSION} (generated by tools/coverage.py)</text>',
    ]
    top = pad + 34
    for i, tactic in enumerate(order):
        x = pad + i * (col_w + gap)
        name = attack["tactics"][tid_of[tactic]]["name"]
        techs = by_tactic.get(tactic, [])
        words, line1, line2 = name.split(), "", ""
        for w in words:
            if len(line1 + " " + w) <= 16 and not line2:
                line1 = (line1 + " " + w).strip()
            else:
                line2 = (line2 + " " + w).strip()
        out.append(f'<rect x="{x}" y="{top}" width="{col_w}" height="{head_h - 6}" rx="4" '
                   f'fill="{EMPTY if not techs else "#e6effa"}"/>')
        out.append(f'<text x="{x + 6}" y="{top + 16}" font-size="11.5" font-weight="600" fill="{INK}">{e(line1)}</text>')
        if line2:
            out.append(f'<text x="{x + 6}" y="{top + 30}" font-size="11.5" font-weight="600" fill="{INK}">{e(line2)}</text>')
        out.append(f'<text x="{x + 6}" y="{top + 45}" font-size="10.5" fill="{INK_MUTED}">'
                   f'{len(techs)} / {totals[tactic]} techniques</text>')
        for j, (tid, score) in enumerate(techs):
            y = top + head_h + j * (cell_h + gap)
            color = SCORE_COLORS[min(score, 3)]
            ink = "#ffffff" if score >= 2 else INK
            tname = attack["techniques"][tid]["name"]
            label = tname if len(tname) <= 19 else tname[:18] + "…"
            out.append(f'<g><title>{e(tid)} {e(tname)} - {score} rule(s)</title>'
                       f'<rect x="{x}" y="{y}" width="{col_w}" height="{cell_h}" rx="4" fill="{color}"/>'
                       f'<text x="{x + 6}" y="{y + 14}" font-size="11" font-weight="600" fill="{ink}">{e(tid)}</text>'
                       f'<text x="{x + 6}" y="{y + 27}" font-size="10" fill="{ink}">{e(label)}</text></g>')
    lx = pad
    out.append(f'<text x="{lx}" y="{legend_y + 14}" font-size="11" fill="{INK_MUTED}">Rules per technique:</text>')
    lx += 122
    for score, label in ((1, "1 rule"), (2, "2 rules"), (3, "3+ rules")):
        out.append(f'<rect x="{lx}" y="{legend_y + 3}" width="14" height="14" rx="3" fill="{SCORE_COLORS[score]}"/>')
        out.append(f'<text x="{lx + 20}" y="{legend_y + 14}" font-size="11" fill="{INK}">{label}</text>')
        lx += 84
    out.append(f'<rect x="{lx}" y="{legend_y + 3}" width="14" height="14" rx="3" fill="{EMPTY}"/>')
    out.append(f'<text x="{lx + 20}" y="{legend_y + 14}" font-size="11" fill="{INK}">tactic not covered</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main() -> int:
    attack, mapping, rules, cells = collect()
    OUT.mkdir(exist_ok=True)
    (OUT / "attack-navigator-layer.json").write_text(
        json.dumps(build_layer(attack, mapping, cells), indent=2) + "\n", encoding="utf-8")
    (OUT / "coverage.md").write_text(build_markdown(attack, mapping, rules, cells), encoding="utf-8")
    (OUT / "coverage-heatmap.svg").write_text(build_svg(attack, cells), encoding="utf-8")
    techs = {t for t, _ in cells}
    print(f"Coverage: {len(rules)} rules -> {len(techs)} techniques; wrote coverage/ "
          "(attack-navigator-layer.json, coverage.md, coverage-heatmap.svg)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
