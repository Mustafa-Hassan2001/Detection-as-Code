#!/usr/bin/env python3
"""Generate SIEM queries from the Sigma rules with sigma-cli.

The files under converted/ are build artefacts: they are produced by this script and
must never be edited by hand. CI regenerates them and fails if the committed copies
differ (`git diff --exit-code converted/`), which guarantees the SIEM content always
matches the reviewed Sigma source.

    python tools/convert.py              # regenerate converted/
    python tools/convert.py --target wazuh
"""

from __future__ import annotations

import argparse
import fnmatch
import importlib.metadata as md
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dac_common import CONFIG_DIR, REPO_ROOT, prime_pysigma_attack_cache, rule_paths  # noqa: E402

OUT_DIR = REPO_ROOT / "converted"
# Prefer the sigma-cli installed next to the running interpreter (the project venv), so
# `make convert` works without activating the venv first.
_VENV_SIGMA = Path(sys.executable).with_name("sigma")
SIGMA = str(_VENV_SIGMA) if _VENV_SIGMA.exists() else (shutil.which("sigma") or "sigma")
HEADER = "GENERATED by tools/convert.py from rules/ - DO NOT EDIT. Run `make convert`."


def sigma_cmd(target: dict, fmt: str, inputs: list[str]) -> list[str]:
    cmd = [SIGMA, "convert", "-t", target["backend"], "-f", fmt]
    for p in target.get("pipelines", []):
        cmd += ["-p", p]
    for key, value in (target.get("backend_options") or {}).items():
        for v in value if isinstance(value, list) else [value]:
            cmd += ["-O", f"{key}={v}"]
    return cmd + inputs


def run(cmd: list[str]) -> tuple[int, str, str]:
    proc = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True)
    return proc.returncode, proc.stdout, proc.stderr


def is_expected_unsupported(target: dict, rel: str) -> bool:
    return any(fnmatch.fnmatch(rel, pat) for pat in target.get("expected_unsupported", []))


def convert_target(name: str, target: dict, rules: list[str], jobs: int) -> tuple[dict, int]:
    tdir = OUT_DIR / name
    if tdir.exists():
        shutil.rmtree(tdir)
    status: dict[str, str] = {}
    failures = 0

    for spec in target["per_rule"]:
        (tdir / spec["dir"]).mkdir(parents=True, exist_ok=True)

    def one(rel: str) -> tuple[str, list[tuple[dict, int, str, str]]]:
        return rel, [(spec, *run(sigma_cmd(target, spec["format"], [rel]))) for spec in target["per_rule"]]

    with ThreadPoolExecutor(max_workers=jobs) as pool:
        for rel, outputs in pool.map(one, rules):
            stem = Path(rel).stem
            for spec, rc, out, err in outputs:
                if rc == 0 and out.strip():
                    (tdir / spec["dir"] / f"{stem}.{spec['extension']}").write_text(
                        out if out.endswith("\n") else out + "\n", encoding="utf-8")
                    status.setdefault(rel, "ok")
                elif is_expected_unsupported(target, rel):
                    status[rel] = "unsupported (expected)"
                else:
                    status[rel] = "FAILED"
                    failures += 1
                    msg = (err.strip().splitlines() or ["no output"])[-1]
                    print(f"  FAILED [{name}/{spec['format']}] {rel}: {msg}")

    supported = [r for r in rules if status.get(r) == "ok"]
    for bundle in target.get("bundles", []):
        rc, out, err = run(sigma_cmd(target, bundle["format"], supported))
        if rc != 0:
            failures += 1
            print(f"  FAILED [{name}/{bundle['format']}] bundle: {err.strip().splitlines()[-1:]}")
            continue
        (tdir / bundle["file"]).write_text(out if out.endswith("\n") else out + "\n", encoding="utf-8")

    ok = sum(1 for s in status.values() if s == "ok")
    skipped = sum(1 for s in status.values() if s.startswith("unsupported"))
    print(f"  {name}: {ok} converted, {skipped} expected-unsupported, {failures} failed")
    return status, failures


def write_manifest(targets: dict, results: dict[str, dict], rules: list[str]) -> None:
    versions = ", ".join(
        f"{pkg} {md.version(pkg)}"
        for pkg in ("sigma-cli", "pySigma", "pySigma-backend-elasticsearch",
                    "pySigma-backend-opensearch", "pySigma-pipeline-sysmon")
    )
    names = list(targets)
    lines = [
        "# Converted SIEM queries",
        "",
        f"> {HEADER}",
        "",
        f"Toolchain: {versions}.",
        "",
        "| Target | Backend | Pipelines | Outputs |",
        "|---|---|---|---|",
    ]
    for n, t in targets.items():
        outs = [f"`{n}/{s['dir']}/*.{s['extension']}`" for s in t["per_rule"]]
        outs += [f"`{n}/{b['file']}`" for b in t.get("bundles", [])]
        lines.append(f"| {n} | `{t['backend']}` | {', '.join(f'`{p}`' for p in t['pipelines'])} "
                     f"| {', '.join(outs)} |")
    lines += ["", "| Rule | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for r in rules:
        lines.append(f"| `{Path(r).stem}` | " + " | ".join(results[n].get(r, "-") for n in names) + " |")
    (OUT_DIR / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--target", action="append", help="only this target (repeatable)")
    ap.add_argument("--jobs", type=int, default=8)
    args = ap.parse_args()

    prime_pysigma_attack_cache()  # SIEM-rule output embeds ATT&CK names: use the pinned release
    targets = yaml.safe_load((CONFIG_DIR / "targets.yml").read_text(encoding="utf-8"))["targets"]
    selected = {k: v for k, v in targets.items() if not args.target or k in args.target}
    rules = [p.relative_to(REPO_ROOT).as_posix() for p in rule_paths()]

    print(f"Converting {len(rules)} rules with {SIGMA}")
    results, failures = {}, 0
    for name, target in selected.items():
        results[name], f = convert_target(name, target, rules, args.jobs)
        failures += f
    if not args.target:
        write_manifest(targets, results, rules)
    print("RESULT: " + ("OK" if not failures else f"{failures} conversion failure(s)"))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
